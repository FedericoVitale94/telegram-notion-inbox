def t(key, **kw):
    """The text `key` in the configured language, with [ui.strings] overrides, filled with kw."""
    import config
    text = config.UI_STRINGS.get(key) or STRINGS.get(config.UI_LANGUAGE, STRINGS["en"]).get(key) or STRINGS["en"][key]
    return text.format(**kw) if kw else text
